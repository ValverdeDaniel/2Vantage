// The generated hide list (Q.5): dropped.yaml → a harness-only stylesheet plus text rules, for OLD pages only.
// Hiding what the plan drops lets the old screen stand for what 2Vantage should look like.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import YAML from 'yaml';

const HERE = path.dirname(fileURLToPath(import.meta.url));

export function loadDropped(file = path.join(HERE, 'dropped.yaml')) {
  const data = YAML.parse(fs.readFileSync(file, 'utf8'));
  const entries = data.dropped || [];
  const bad = entries.filter((e) => !e.id || !/^(Drop|Defer)$/.test(e.verdict) || !(e.selector || e.text || e.skip));
  if (bad.length) throw new Error(`dropped.yaml: entries need an id, a Drop/Defer verdict and a selector, text or skip: ${bad.map((e) => e.id).join(', ')}`);
  return { entries, layout: data.layout || [] };
}

// The stylesheet, one rule per entry, labelled with its item so a reviewer can trace every hidden element.
export function stylesheet({ entries, layout }) {
  const rules = entries
    .filter((e) => e.selector && !e.keep && !e.skip)
    .map((e) => `/* ${e.id} ${e.verdict}: ${String(e.what).replace(/\*\//g, '')} */\n${e.selector} { display: none !important; }`);
  const steady = layout.map((l) => `/* steadies ${l.for} */\n${l.css}`);
  return `/* Generated by browser/look/hide.mjs from dropped.yaml. Injected into old Vantage pages only. */\n${[...rules, ...steady].join('\n')}\n`;
}

export function textRules({ entries }) {
  return entries.filter((e) => e.text && !e.selector && !e.keep && !e.skip).map((e) => ({ id: e.id, text: e.text, within: e.within || '*' }));
}

export function writeStylesheet(dir, dropped) {
  const file = path.join(dir, 'dropped.css');
  fs.writeFileSync(file, stylesheet(dropped));
  return file;
}

// Apply both to a loaded old page. Returns the item IDs that hid something on it.
export async function hideOnOldPage(page, dropped) {
  await page.addStyleTag({ content: stylesheet(dropped) });
  const hits = await page.evaluate(({ entries, rules }) => {
    const found = new Set();
    for (const e of entries) {
      try {
        if ([...document.querySelectorAll(e.selector)].length) found.add(e.id);
      } catch {
        // a selector this Chrome cannot parse hides nothing; the report lists the item as unseen
      }
    }
    for (const rule of rules) {
      for (const el of document.querySelectorAll(rule.within)) {
        if (el.textContent.includes(rule.text)) {
          el.style.setProperty('display', 'none', 'important');
          found.add(rule.id);
        }
      }
    }
    return [...found];
  }, {
    entries: dropped.entries.filter((e) => e.selector && !e.keep && !e.skip).map(({ id, selector }) => ({ id, selector })),
    rules: textRules(dropped),
  });
  return hits.sort();
}
