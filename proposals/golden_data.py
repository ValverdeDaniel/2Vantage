def alt(plan_type, deductible, oop=None, pcp=None):
    """A quoted plan's required details: funding, type, deductible, out-of-pocket max and PCP copay."""
    default_oop, default_pcp = DESIGN_BY_TYPE[plan_type]
    return {
        'funding': 'fully_insured',
        'plan_type': plan_type,
        'deductible_single': deductible,
        'oop_max_single': oop or default_oop,
        'pcp_copay': pcp or default_pcp,
    }


