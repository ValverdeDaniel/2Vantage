T = ('EE', 'ES', 'EC', 'FAM')


def rates(ee, es, ec, fam):
    return {'rate_ee': ee, 'rate_es': es, 'rate_ec': ec, 'rate_fam': fam}


def counts(ee, es, ec, fam):
    return dict(zip(T, (ee, es, ec, fam), strict=True))


